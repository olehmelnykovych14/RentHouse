#!/usr/bin/env python3
"""
Спільна рубрика розпізнавання «власник ↔ посередник» для всіх джерел.

Навіщо окремий модуль: OLX і Telegram мали власні промпти, які розійшлися між
собою — те саме оголошення отримувало різні оцінки залежно від того, звідки
прийшло. Критерії мають бути одні, покращення — в одному місці.

Головний прийом: модель СПОЧАТКУ виписує знайдені сигнали цитатами з тексту,
і лише потім ставить оцінку. Порядок полів у схемі = порядок генерації, тож
число з'являється вже після того, як модель перелічила докази. Раніше вона
одразу писала оцінку й «обґрунтовувала» її заднім числом — звідси і взялася
купа однакових 70% з формулюванням «автор може бути власником».
"""

# ─────────────────────────────────────────────
# Схема: сигнали ПЕРЕД оцінкою (порядок важливий)
# ─────────────────────────────────────────────

POST_TYPE_PROPERTY = {
    "post_type": {
        "type": "string",
        "enum": ["rent_offer", "sale", "wanted", "spam", "other"],
        "description": (
            "rent_offer — ПРОПОЗИЦІЯ здати житло (здам, здається, оренда). "
            "sale — продаж житла чи ділянки. "
            "wanted — ЗАПИТ: автор САМ шукає житло або хоче купити "
            "(шукаю, шукаємо, зніму, куплю, розглянемо варіанти). "
            "spam — реклама, боти, добірки посилань, не конкретне житло. "
            "other — решта."
        ),
    },
}

SIGNAL_PROPERTIES = {
    "owner_signals": {
        "type": "array",
        "items": {"type": "string"},
        "description": (
            "Короткі ЦИТАТИ з тексту, що вказують на власника. Тільки те, що "
            "справді є в тексті — не вигадувати й не переказувати. Порожній "
            "масив, якщо таких ознак немає."
        ),
    },
    "realtor_signals": {
        "type": "array",
        "items": {"type": "string"},
        "description": (
            "Короткі ЦИТАТИ з тексту, що вказують на посередника. Тільки те, "
            "що справді є в тексті. Порожній масив, якщо таких ознак немає."
        ),
    },
}

# ─────────────────────────────────────────────
# Рубрика
# ─────────────────────────────────────────────

RUBRIC = """Ти визначаєш, хто подав оголошення про оренду в Україні: ВЛАСНИК житла чи ПОСЕРЕДНИК (рієлтор, агентство).

ПОРЯДОК РОБОТИ — не порушувати:
1) post_type: це взагалі пропозиція оренди? Канали й дошки повні продажу,
   запитів «шукаю житло» та реклами. Все, крім rent_offer, далі не аналізуємо.
2) owner_signals і realtor_signals: виписати ЦИТАТИ з тексту. Не переказ, не
   здогад — саме фрагменти тексту. Немає ознак — порожній масив.
3) probability_of_owner: оцінка, що спирається САМЕ на виписані цитати.

ОЗНАКИ ВЛАСНИКА (owner_signals):
+ Пряма заява від першої особи: «здаю свою квартиру», «я власник», «моя квартира»
+ Побутові подробиці, які знає лише мешканець: «шафа залишається», «сусіди тихі»,
  «вікна на схід», «лічильники двозонні», «холодильник купили торік»
+ Особиста причина здачі: «переїжджаємо», «син вивчився і виїхав»
+ Особисті умови до мешканців: «без тварин», «можна студентам», «краще сім'ї»
+ Неформальна мова, нерівне форматування, помилки, текст «від руки»
+ Один конкретний об'єкт без згадки інших варіантів

ОЗНАКИ ПОСЕРЕДНИКА (realtor_signals):
- Слова «рієлтор», «ріелтор», «агенція», «агентство», «АН», «код об'єкта», «маклер»
- Згадка комісії в будь-якому вигляді: «комісія 50%», «послуги агента», «оплата послуг»
- «Є ще варіанти», «підберемо», «база квартир», «великий вибір», «інші пропозиції»
- Рекламні штампи: «ідеальний варіант», «затишне гніздечко», «бізнес-клас»,
  «розвинена інфраструктура», «поспішайте», «терміново»
- Ідеально структурований шаблон: рядки з емодзі-маркерами, однакові блоки полів
- «Деталі в приват», «відео надішлю», «дзвоніть у робочий час», «працюємо щодня»
- Заклик до перегляду через офіс, юридичний супровід, «чистота угоди»

ВАЖЛИВО про «без комісії»: фраза «без комісії» НЕ означає власника. Так пишуть і
агентства, яким платить власник. Це ознака посередника, а не проти нього.

КАЛІБРУВАННЯ probability_of_owner — оцінка має відповідати доказам:
  90-100 — є пряма заява про власність («здаю свою», «я власник») І немає
           жодного realtor_signal
  75-89  — кілька побутових подробиць, характерних для мешканця, realtor_signals
           порожній
  50-74  — текст нейтральний, виразних ознак немає в жодну сторону
  20-49  — є хоча б один realtor_signal
  0-19   — прямі ознаки посередника (агенція, комісія, «є ще варіанти»)

ЯКЩО СУМНІВАЄШСЯ — СТАВ НИЖЧУ ОЦІНКУ. Пропустити рієлтора в каталог «квартир
від власників» набагато гірше, ніж відсіяти власника: користувач платить саме
за відсутність посередників. Нейтральний текст без ознак власника — це 50-60,
а не 70+."""


def build_system_prompt(extra: str = "") -> str:
    """Рубрика + інструкції з витягування полів конкретного джерела."""
    return RUBRIC + ("\n\n" + extra if extra else "")


# ─────────────────────────────────────────────
# Узгодженість оцінки з доказами
# ─────────────────────────────────────────────

def calibrate(extraction: dict) -> dict:
    """
    Приводить оцінку у відповідність до виписаних сигналів.

    Модель іноді перелічує ознаки посередника й одразу ставить високий бал —
    суперечність, яку раніше ніхто не ловив. Тут докази мають пріоритет над
    числом: якщо realtor_signals не порожній, оцінка не може лишатись високою.
    """
    prob = int(extraction.get("probability_of_owner") or 0)
    realtor = extraction.get("realtor_signals") or []
    owner = extraction.get("owner_signals") or []

    if realtor and prob > 49:
        extraction["probability_of_owner"] = 40
        extraction["reasoning"] = (
            f"Оцінку знижено з {prob} до 40: у тексті є ознаки посередника "
            f"({'; '.join(realtor[:3])}). " + (extraction.get("reasoning") or "")
        )
    elif not owner and prob > 74:
        # Висока оцінка без жодної цитати на користь власника — це здогад.
        extraction["probability_of_owner"] = 60
        extraction["reasoning"] = (
            f"Оцінку знижено з {prob} до 60: жодної ознаки власника в тексті "
            "не наведено. " + (extraction.get("reasoning") or "")
        )
    return extraction
