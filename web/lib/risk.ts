/**
 * Мітки ризику для оголошення — щоб орендар був насторожі. Евристика з тексту
 * (типові ознаки орендного шахрайства в Україні) + сигнал «дешевше за ринок».
 * Без AI й без нових колонок: працює на всіх наявних оголошеннях одразу.
 * Клієнт-безпечно (чиста функція, без серверних імпортів).
 *
 * Тон — «варто перевірити», а не звинувачення: це підказка, не вирок.
 */

export type RiskFlag = { label: string; detail: string; high: boolean };

const PATTERNS: { re: RegExp; label: string; detail: string; high: boolean }[] = [
  {
    re: /передоплат|предоплат|аванс[^.]{0,30}карт|завдаток[^.]{0,30}(перегляд|карт)|перекаж[іи]ть|задаток[^.]{0,30}карт/i,
    label: "Просять передоплату",
    detail: "Оплата до перегляду квартири — типова ознака шахрайства. Не переказуйте кошти, поки не побачили житло особисто.",
    high: true,
  },
  {
    re: /за кордоном|ключ[іи][^.]{0,30}пошт|надішл[^.]{0,20}ключ|документи[^.]{0,20}пошт/i,
    label: "«Власник за кордоном»",
    detail: "Схема, де власник «за кордоном», а ключі надішле поштою після оплати — класичне шахрайство.",
    high: true,
  },
  {
    re: /брон[ьюі][^.]{0,20}(карт|оплат)|резерв[^.]{0,20}оплат|застав[^.]{0,20}до перегляд/i,
    label: "Оплата за «бронь»",
    detail: "Прохання заплатити за резерв до перегляду — не робіть цього.",
    high: true,
  },
  {
    re: /тільки (в )?(телеграм|telegram|вайбер|viber|whatsapp|ватсап)|не дзвон|лише пиш|дзвінки не прийма/i,
    label: "Уникає дзвінків",
    detail: "Готовність спілкуватися лише в месенджері — привід бути обережним.",
    high: false,
  },
  {
    re: /терміново|тільки сьогодні|встигніть|поспіш|останній день|встигни/i,
    label: "Тиск терміновістю",
    detail: "«Терміново / тільки сьогодні» підганяє прийняти рішення без перевірки.",
    high: false,
  },
];

/** Повертає мітки ризику. `belowMarket` — ціна помітно нижча за схожі. */
export function riskFlags(
  text: string | null | undefined,
  opts: { belowMarket?: boolean } = {}
): RiskFlag[] {
  const flags: RiskFlag[] = [];
  const t = text || "";
  for (const p of PATTERNS) {
    if (p.re.test(t)) flags.push({ label: p.label, detail: p.detail, high: p.high });
  }
  if (opts.belowMarket) {
    flags.push({
      label: "Ціна нижча за ринок",
      detail: "Помітно дешевше за схожі квартири в цьому місті. Занизька ціна часто буває приманкою — перевірте уважно.",
      high: true,
    });
  }
  return flags;
}
